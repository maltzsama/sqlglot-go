"""Generate optimizer/func_sql_names.go: Func.sql_name() for every upstream function class.

Run from the repo root, with the pinned reference fetched:

    PYTHONPATH=.reference/sqlglot-v30.17.0 python3 -I scripts/gen_func_sql_names.py

simplify's gen() pseudo-generator names a function by sql_name() (optimizer/simplify.py:1844),
and the strings it builds decide the operand order uniq_sort produces, so the names must match
upstream exactly.
"""

import os
import sys

sys.path.insert(0, os.environ.get("PYTHONPATH", ".reference/sqlglot-v30.17.0"))

from sqlglot import exp  # noqa: E402
from sqlglot.helper import subclasses  # noqa: E402


def main() -> None:
    names = {}
    for cls in subclasses(exp.__name__, exp.Func, (exp.Func, exp.AggFunc)):
        try:
            names[cls.__name__] = cls.sql_name()
        except (NotImplementedError, AssertionError):
            continue
    out = [
        "// Code generated by scripts/gen_func_sql_names.py from sqlglot v30.17.0; DO NOT EDIT.",
        "",
        "package optimizer",
        "",
        "// funcSQLNames maps an upstream function class name to its Func.sql_name().",
        "var funcSQLNames = map[string]string{",
    ]
    for name in sorted(names):
        out.append(f'\t"{name}": "{names[name]}",')
    out.append("}")
    out.append("")
    with open("optimizer/func_sql_names.go", "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
