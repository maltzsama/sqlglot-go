package sqlglot_test

import (
	"testing"

	sqlglot "github.com/maltzsama/sqlglot-go"
	"github.com/maltzsama/sqlglot-go/generator"
)

// TestMaterializeIdentity is the same-dialect round-trip oracle for Materialize,
// ported from .reference/sqlglot-v30.17.0/tests/dialects/test_materialize.py. Cases
// are already in their canonical Materialize spelling; NOW() generating
// CURRENT_TIMESTAMP is upstream's own expected rewrite, not a gap.
func TestMaterializeIdentity(t *testing.T) {
	cases := []struct {
		sql      string
		want     string
		pretty   bool
		identify bool
	}{
		{sql: `CURRENT_TIMESTAMP`, want: `CURRENT_TIMESTAMP`},
		{sql: `NOW()`, want: `CURRENT_TIMESTAMP`},
		{sql: `MZ_NOW()`, want: `MZ_NOW()`},
		{sql: `SELECT CAST(1 AS mz_timestamp)`, want: `SELECT CAST(1 AS mz_timestamp)`},
		{sql: `CREATE TABLE example (id INT, name LIST)`, want: `CREATE TABLE example (id INT, name LIST)`},
		{sql: `SELECT LIST[]`, want: `SELECT LIST[]`},
		{sql: `SELECT LIST[1, 2, 3]`, want: `SELECT LIST[1, 2, 3]`},
		{sql: `SELECT LIST[LIST[1], LIST[2], NULL]`, want: `SELECT LIST[LIST[1], LIST[2], NULL]`},
		{sql: `SELECT CAST(LIST[1, 2, 3] AS INT LIST)`, want: `SELECT CAST(LIST[1, 2, 3] AS INT LIST)`},
		{sql: `SELECT CAST(NULL AS INT LIST)`, want: `SELECT CAST(NULL AS INT LIST)`},
		{sql: `SELECT CAST(NULL AS INT LIST LIST LIST)`, want: `SELECT CAST(NULL AS INT LIST LIST LIST)`},
		{sql: `SELECT LIST(SELECT 1)`, want: `SELECT LIST(SELECT 1)`},
		{sql: `SELECT MAP[]`, want: `SELECT MAP[]`},
		{sql: `SELECT MAP['a' => MAP['b' => 'c']]`, want: `SELECT MAP['a' => MAP['b' => 'c']]`},
		{sql: `SELECT CAST(MAP['a' => 1] AS MAP[TEXT => INT])`, want: `SELECT CAST(MAP['a' => 1] AS MAP[TEXT => INT])`},
		{sql: `SELECT CAST(NULL AS MAP[TEXT => INT])`, want: `SELECT CAST(NULL AS MAP[TEXT => INT])`},
		{sql: `SELECT CAST(NULL AS MAP[TEXT => MAP[TEXT => INT]])`, want: `SELECT CAST(NULL AS MAP[TEXT => MAP[TEXT => INT]])`},
		{sql: `SELECT MAP(SELECT 'a', 1)`, want: `SELECT MAP(SELECT 'a', 1)`},
	}
	for _, c := range cases {
		t.Run(c.sql, func(t *testing.T) {
			expr, err := sqlglot.ParseOne(c.sql, "materialize")
			if err != nil {
				t.Fatalf("ParseOne: %v", err)
			}
			got, err := sqlglot.Generate(expr, "materialize", generator.Options{Pretty: c.pretty, Identify: c.identify})
			if err != nil {
				t.Fatalf("Generate: %v", err)
			}
			if got != c.want {
				t.Fatalf("round-trip mismatch\n want: %s\n  got: %s", c.want, got)
			}
		})
	}
}

// TestMaterializeCrossDialect ports the validate_all arms of test_materialize.py:
// "read" rows parse with the named dialect and regenerate with materialize, "write"
// rows parse with materialize and regenerate with the named dialect.
func TestMaterializeCrossDialect(t *testing.T) {
	cases := []struct {
		kind     string // "read": parse dialect, generate materialize; "write": parse materialize, generate dialect
		sql      string
		dialect  string
		want     string
		pretty   bool
		identify bool
	}{
		{kind: "write", sql: `CREATE TABLE example (id INT PRIMARY KEY, name TEXT)`, dialect: "materialize", want: `CREATE TABLE example (id INT, name TEXT)`},
		{kind: "write", sql: `CREATE TABLE example (id INT PRIMARY KEY, name TEXT)`, dialect: "postgres", want: `CREATE TABLE example (id INT PRIMARY KEY, name TEXT)`},
		{kind: "write", sql: `INSERT INTO example (id, name) VALUES (1, 'Alice') ON CONFLICT(id) DO NOTHING`, dialect: "materialize", want: `INSERT INTO example (id, name) VALUES (1, 'Alice')`},
		{kind: "write", sql: `INSERT INTO example (id, name) VALUES (1, 'Alice') ON CONFLICT(id) DO NOTHING`, dialect: "postgres", want: `INSERT INTO example (id, name) VALUES (1, 'Alice') ON CONFLICT(id) DO NOTHING`},
		{kind: "write", sql: `CREATE TABLE example (id SERIAL, name TEXT)`, dialect: "materialize", want: `CREATE TABLE example (id INT NOT NULL, name TEXT)`},
		{kind: "write", sql: `CREATE TABLE example (id SERIAL, name TEXT)`, dialect: "postgres", want: `CREATE TABLE example (id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL, name TEXT)`},
		{kind: "write", sql: `CREATE TABLE example (id INT AUTO_INCREMENT, name TEXT)`, dialect: "materialize", want: `CREATE TABLE example (id INT NOT NULL, name TEXT)`},
		{kind: "write", sql: `CREATE TABLE example (id INT AUTO_INCREMENT, name TEXT)`, dialect: "postgres", want: `CREATE TABLE example (id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL, name TEXT)`},
		{kind: "write", sql: `SELECT JSON_EXTRACT_PATH_TEXT('{ "farm": {"barn": { "color": "red", "feed stocked": true }}}', 'farm', 'barn', 'color')`, dialect: "materialize", want: `SELECT JSON_EXTRACT_PATH_TEXT('{ "farm": {"barn": { "color": "red", "feed stocked": true }}}', 'farm', 'barn', 'color')`},
		{kind: "write", sql: `SELECT JSON_EXTRACT_PATH_TEXT('{ "farm": {"barn": { "color": "red", "feed stocked": true }}}', 'farm', 'barn', 'color')`, dialect: "postgres", want: `SELECT JSON_EXTRACT_PATH_TEXT('{ "farm": {"barn": { "color": "red", "feed stocked": true }}}', 'farm', 'barn', 'color')`},
		{kind: "write", sql: `SELECT MAP['a' => 1]`, dialect: "materialize", want: `SELECT MAP['a' => 1]`},
	}
	for _, c := range cases {
		read, write := "materialize", "materialize"
		if c.kind == "read" {
			read = c.dialect
		} else {
			write = c.dialect
		}
		t.Run(c.kind+" "+c.dialect+" "+c.sql, func(t *testing.T) {
			expr, err := sqlglot.ParseOne(c.sql, read)
			if err != nil {
				t.Fatalf("ParseOne(%q, read=%q): %v", c.sql, read, err)
			}
			got, err := sqlglot.Generate(expr, write, generator.Options{Pretty: c.pretty, Identify: c.identify})
			if err != nil {
				t.Fatalf("Generate(%q, write=%q): %v", c.sql, write, err)
			}
			if got != c.want {
				t.Fatalf("read=%q write=%q mismatch\n want: %s\n  got: %s", read, write, c.want, got)
			}
		})
	}
}
