// Doris ports the Apache Doris dialect class from
// .reference/sqlglot-v30.17.0/sqlglot/dialects/doris.py:8-15. Like StarRocks, Doris extends
// MySQL; the parser-override and generator dispatch chains inherit the mysql tables.
func Doris() *Dialect {
	d := MySQL()
	d.Name = "doris"

	// generators/doris.py:26-31/40-45 generator flags.
	d.VarcharRequiresSize = false
	d.SupportsAlterColumnNullability = false
	d.WithPropertiesPrefix = "PROPERTIES"
	d.RenameTableWithDB = false
	d.UpdateStatementSupportsFrom = true

	// parsers/doris.py:27-49 FUNCTIONS overlay on top of MySQL's.
	merged := make(map[string]func([]exp.Expression) exp.Expression, len(d.Functions)+14)
	for name, builder := range d.Functions {
		merged[name] = builder
	}
	for name, builder := range dorisFunctions() {
		merged[name] = builder
	}
	d.Functions = merged

	// generators/doris.py:93-564 RESERVED_KEYWORDS.
	d.ReservedKeywords = dorisReservedKeywords()

	return d
}

